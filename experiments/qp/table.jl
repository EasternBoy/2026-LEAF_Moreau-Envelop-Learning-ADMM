# Run from any directory: julia --project=. experiments/qp/table.jl
const REPO = abspath(joinpath(@__DIR__, "..", ".."))
using Pkg
Base.active_project() == joinpath(REPO, "Project.toml") || Pkg.activate(REPO; io = devnull)
using Printf, Random, SparseArrays, LinearAlgebra, NPZ, JuMP, Statistics
using Distributions

const OUT = joinpath(REPO, "results", "qp", "table")
const INST_DIR = joinpath(OUT, "instances")
cd(REPO)

const FloatType = Float64
const n = 100
const neq = 50
const m = 50
const N_SAMPLES = 1000
const SLME_TOL = 1e-2
const SLME_FEAS_TOL = 1e-6
const MAX_ITER = 1000
const max_opt_gap::FloatType = parse(FloatType, get(ENV, "QP_GOPT", "1.0")) # objective-gap target (%)
const SEED = 20260923
const OSQP_TOL = 1e-8
const SUFFIX = "n=$(n)-neq=$(neq)-m=$(m)-samples=$(N_SAMPLES)"
@assert N_SAMPLES > 0 && SLME_TOL > 0 && MAX_ITER > 0

include(joinpath(REPO, "problems", "qp", "problem.jl"))
include(joinpath(REPO, "problems", "qp", "setup.jl"))
include(joinpath(REPO, "problems", "qp", "jump_solver.jl"))
include(joinpath(REPO, "problems", "qp", "lme_admm.jl"))

function instances()
    path = joinpath(INST_DIR, "instances-$(SUFFIX).npz")
    if isfile(path)
        saved = npzread(path)
        @assert all(saved[key] ≈ qp_data[key] for key in ("Q", "p", "A", "G", "h"))
        return saved["X"]
    end
    Random.seed!(SEED)
    data_opt(n, neq, m) # Skip the warmup draw, matching benchmark.jl.
    X = reduce(vcat, [permutedims(data_opt(n, neq, m).x) for _ in 1:N_SAMPLES])
    mkpath(INST_DIR)
    npzwrite(path, Dict("X" => X, "seed" => SEED,
                       (key => qp_data[key] for key in ("Q", "p", "A", "G", "h"))...))
    return X
end

instance(X, k) = data_opt(; x = Vector{Float64}(X[k, :]))

function score(X, W, Jopt)
    eq = abs.(W * qp_data["A"]' - X)
    ineq = max.(W * qp_data["G"]' .- qp_data["h"]', 0.0)
    J = [get_objective(instance(X, k), Vector{Float64}(W[k, :])) for k in 1:N_SAMPLES]
    max_eq = vec(maximum(eq; dims = 2))
    max_ineq = vec(maximum(ineq; dims = 2))
    return Dict("objective" => J,
                "gap_pct" => 100 .* abs.(J - Jopt) ./ max.(abs.(Jopt), eps(Float64)),
                "max_eq" => max_eq, "mean_eq" => vec(mean(eq; dims = 2)),
                "max_ineq" => max_ineq, "mean_ineq" => vec(mean(ineq; dims = 2)),
                "max_viol" => max.(max_eq, max_ineq))
end

function save_result(method, tol, X, W, times, Jopt)
    result = merge(score(X, W, Jopt),
                   Dict("W" => W, "time_ms" => 1e3 .* times, "seed" => SEED,
                        "tol" => tol, "samples" => N_SAMPLES, "oracle_assisted" => false))
    if method == "sLME-ADMM"
        result["oracle_assisted"] = true
        result["max_opt_gap"] = max_opt_gap
        result["max_iter"] = MAX_ITER
        result["feas_tol"] = SLME_FEAS_TOL
        result["projection_setup_excluded"] = true
    end
    gap_suffix = method == "sLME-ADMM" ? "-gopt=$(max_opt_gap)" : ""
    npzwrite(joinpath(OUT, "$(method)-$(SUFFIX)-tol=$(tol)$(gap_suffix).npz"), result)
    return result
end

function render(results)
    rows = String[]
    for (method, result) in results
        push!(rows, @sprintf("| %s | %.5f | %.5e | %.5e | %.5e | %.5e | %.6f | %.3g (%.3g) |",
              method, mean(result["objective"]), mean(result["max_eq"]), mean(result["mean_eq"]),
              mean(result["max_ineq"]), mean(result["mean_ineq"]), mean(result["time_ms"])/1e3,
              mean(result["gap_pct"]), maximum(result["gap_pct"])))
    end
    md = """
    # QP benchmark

    Generated by `experiments/qp/table.jl`: $(N_SAMPLES) saved instances with
    (n, neq, m) = ($(n), $(neq), $(m)), seed $(SEED).
    OSQP tolerance: $(OSQP_TOL). sLME-ADMM consensus tolerance: $(SLME_TOL),
    maximum iterations: $(MAX_ITER), objective-gap target: ≤ $(max_opt_gap)%.
    Objective, violation, and time columns are means across instances;
    Max eq. and Max ineq. are per-instance maxima before averaging.
    Equality violations are absolute residuals; inequality violations are positive parts,
    both in original coordinates. Time is in seconds, with compilation excluded.
    sLME-ADMM factorizes its projection per solve; setup is excluded from its internal solve time.
    sLME-ADMM stopping requires consensus residual < $(SLME_TOL), original-coordinate
    equality/inequality violation ≤ $(SLME_FEAS_TOL), and objective gap ≤ $(max_opt_gap)%,
    using OSQP's known optimum.
    Opt. gap is reported in percent as mean (maximum) across instances.
    Parenthesized deviations across repeated runs are omitted for this single run.

    | Method | Obj. value | Max eq. | Mean eq. | Max ineq. | Mean ineq. | Time (s) | Opt. gap (%) mean (max) |
    |---|---|---|---|---|---|---|---|
    $(join(rows, "\n"))
    """
    write(joinpath(OUT, "qp_table-$(SUFFIX)-tol=$(SLME_TOL)-gopt=$(max_opt_gap).md"), md)
    println(md)
end

function main()
    X = instances()
    mkpath(OUT)
    warm = instance(X, 1)
    gradient = gradient_struct(model, 1, n)
    _, _, warm_J = JuMP_solver("osqp", warm, OSQP_TOL)
    global J_opt = warm_J
    sLME_ADMM(warm, gradient, sLME_ADMM_callback; tol = SLME_TOL,
              feas_tol = SLME_FEAS_TOL, max_iter = MAX_ITER)
    Wopt = zeros(N_SAMPLES, n); Wslme = similar(Wopt)
    Topt = zeros(N_SAMPLES); Tslme = similar(Topt); Jopt = similar(Topt)
    for k in 1:N_SAMPLES
        data = instance(X, k)
        Wopt[k, :], Topt[k], Jopt[k] = JuMP_solver("osqp", data, OSQP_TOL)
        global J_opt = Jopt[k]
        Wslme[k, :], Tslme[k], _ = sLME_ADMM(data, gradient, sLME_ADMM_callback; tol = SLME_TOL,
                                            feas_tol = SLME_FEAS_TOL, max_iter = MAX_ITER)
        k % 5 == 0 && GC.gc()
        k % 100 == 0 && println("Completed $k / $N_SAMPLES instances")
    end
    npzwrite(joinpath(OUT, "ground_truth-$(SUFFIX).npz"),
             Dict("W" => Wopt, "J_opt" => Jopt, "time_ms" => 1e3 .* Topt,
                  "seed" => SEED, "tol" => OSQP_TOL))
    osqp = save_result("OSQP", OSQP_TOL, X, Wopt, Topt, Jopt)
    slme = save_result("sLME-ADMM", SLME_TOL, X, Wslme, Tslme, Jopt)
    render([("Optimizer (OSQP)", osqp), ("sLME-ADMM", slme)])
end

if abspath(PROGRAM_FILE) == @__FILE__
    main()
end
